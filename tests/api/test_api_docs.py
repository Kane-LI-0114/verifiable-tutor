"""The committed API documentation bundle stays in sync with the app.

``docs/api/`` is the maintained, offline Swagger UI bundle. These tests fail
when the committed OpenAPI schema or the generated page drifts from the app.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCS_DIR = REPO_ROOT / "docs" / "api"
SCRIPT = REPO_ROOT / "scripts" / "build_api_docs.py"


def test_committed_openapi_json_matches_the_app_schema():
    from verifiable_tutor.api.docs import build_openapi_spec, dump_spec

    committed = DOCS_DIR / "openapi.json"
    assert committed.is_file(), "run .venv/bin/python scripts/build_api_docs.py"

    expected = dump_spec(build_openapi_spec())
    assert committed.read_text(encoding="utf-8") == expected, (
        "docs/api/openapi.json is stale; run .venv/bin/python scripts/build_api_docs.py"
    )


def test_build_script_check_mode_passes():
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 0, result.stdout + result.stderr


def test_generated_index_embeds_the_spec_and_uses_only_local_assets():
    import re

    page = DOCS_DIR / "index.html"
    assert page.is_file(), "run .venv/bin/python scripts/build_api_docs.py"
    html = page.read_text(encoding="utf-8")

    assert "Generated by scripts/build_api_docs.py" in html
    assert '<script type="application/json" id="openapi-spec">' in html
    assert "SwaggerUIBundle" in html
    references = re.findall(r'(?:src|href)="([^"]+)"', html)
    assert references, "the page should reference vendored assets"
    assert all(not reference.startswith(("http://", "https://")) for reference in references)
    assert all("vendor/swagger-ui/" in reference for reference in references)
    assert "cdn.jsdelivr" not in html


def test_vendored_swagger_ui_assets_are_pinned_and_intact():
    import hashlib

    vendor = DOCS_DIR / "vendor" / "swagger-ui"
    version = (vendor / "VERSION").read_text(encoding="utf-8").strip()
    assert version == "5.34.1"

    listed: dict[str, str] = {}
    for line in (vendor / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        digest, name = line.split()
        listed[name] = digest
    assert set(listed) == {
        "swagger-ui-bundle.js",
        "swagger-ui.css",
        "favicon-32x32.png",
        "LICENSE",
    }
    for name, expected in listed.items():
        data = (vendor / name).read_bytes()
        assert hashlib.sha256(data).hexdigest() == expected, f"{name} checksum mismatch"
    license_text = (vendor / "LICENSE").read_text(encoding="utf-8")
    assert "Apache License" in license_text


def test_docs_route_serves_the_local_swagger_ui(docs_api):
    page = docs_api.client.get("/docs")

    assert page.status_code == 200
    assert "/api-docs/vendor/swagger-ui/swagger-ui-bundle.js" in page.text
    assert "/api-docs/vendor/swagger-ui/swagger-ui.css" in page.text
    assert "cdn.jsdelivr" not in page.text
    assert "Swagger UI" in page.text


def test_api_docs_static_bundle_is_mounted(docs_api):
    index = docs_api.client.get("/api-docs/")
    assert index.status_code == 200
    assert "SwaggerUIBundle" in index.text

    bundle = docs_api.client.get("/api-docs/vendor/swagger-ui/swagger-ui-bundle.js")
    assert bundle.status_code == 200
    assert len(bundle.content) > 1_000_000

    spec = docs_api.client.get("/api-docs/openapi.json")
    assert spec.status_code == 200
    assert spec.json()["openapi"].startswith("3.")


def test_missing_docs_bundle_disables_the_swagger_routes(missing_docs_api):
    assert missing_docs_api.client.get("/docs").status_code == 404
    assert missing_docs_api.client.get("/api-docs/").status_code == 404
    assert missing_docs_api.client.get("/openapi.json").status_code == 200
