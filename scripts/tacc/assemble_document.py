#!/usr/bin/env python3
"""Assemble one document markdown from the per-page OCR records.

Reads the page JSONL written by ``ocr_pages.py`` and writes a single markdown
file with ``<!-- page: N -->`` markers in page order, plus a small front matter
with the document identity and page count.

Usage:
  run_proot "$VT_PYTHON" assemble_document.py --jsonl pages.jsonl \
      --out course_project-ocr.md --doc-id course_project
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--jsonl", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--doc-id", required=True)
    parser.add_argument("--pdf", default="")
    parser.add_argument("--pdf-sha256", default="")
    args = parser.parse_args()

    records = []
    for line in Path(args.jsonl).read_text(encoding="utf-8").splitlines():
        if line.strip():
            records.append(json.loads(line))
    records.sort(key=lambda record: int(record.get("page_no", 0)))

    pages_ok = sum(1 for record in records if record.get("status") == "ok")
    blocks = sum(len(record.get("blocks") or []) for record in records)
    chars = sum(len(record.get("text") or "") for record in records)

    lines = [
        f"# {args.doc_id}",
        "",
        "<!-- generated by tacc/pdf-parse; one section per PDF page -->",
        "",
        f"- source pdf: {args.pdf or args.doc_id}",
        f"- pdf sha256: {args.pdf_sha256 or hashlib.sha256(args.doc_id.encode()).hexdigest()[:16]}",
        f"- pages: {len(records)} ({pages_ok} parsed ok)",
        f"- blocks: {blocks}",
        f"- characters: {chars}",
        "",
    ]
    for record in records:
        page_no = int(record.get("page_no", 0))
        lines.append(f"<!-- page: {page_no} -->")
        lines.append("")
        markdown = (record.get("markdown") or "").strip()
        if not markdown:
            markdown = (record.get("text") or "").strip()
        if record.get("status") != "ok":
            markdown = f"> page failed: {record.get('error', 'unknown error')}"
        lines.append(markdown if markdown else "> (empty page)")
        lines.append("")

    target = Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"[assemble] pages={len(records)} ok={pages_ok} blocks={blocks} chars={chars} out={target}",
        flush=True,
    )
    return 0 if pages_ok == len(records) else 1


if __name__ == "__main__":
    sys.exit(main())
