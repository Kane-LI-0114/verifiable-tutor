def write_bundle() -> list[Path]:
    """Write the committed markdown and Graphviz files from the current schema."""

    snapshot = build_snapshot()
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOT_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(render_markdown(snapshot), encoding="utf-8")
    DOT_PATH.write_text(render_dot(snapshot), encoding="utf-8")
    return [DOC_PATH, DOT_PATH]


def check_bundle() -> list[str]:
    """Return staleness problems for the committed physical model files."""

    snapshot = build_snapshot()
    problems: list[str] = []
    expected_doc = render_markdown(snapshot)
    expected_dot = render_dot(snapshot)
    if not DOC_PATH.is_file():
        problems.append(f"missing {DOC_PATH}")
    elif DOC_PATH.read_text(encoding="utf-8") != expected_doc:
        problems.append(f"stale {DOC_PATH}")
    if not DOT_PATH.is_file():
        problems.append(f"missing {DOT_PATH}")
    elif DOT_PATH.read_text(encoding="utf-8") != expected_dot:
        problems.append(f"stale {DOT_PATH}")
    return problems

