class SchemaDocsError(RuntimeError):
    """Raised when the physical schema cannot be rendered faithfully."""


@dataclass(frozen=True)
class Column:
    name: str
    sql_type: str
    nullable: bool
    default: str | None
    primary_key: bool


@dataclass(frozen=True)
class ForeignKey:
    column: str
    references_table: str
    references_column: str
    on_delete: str


@dataclass(frozen=True)
class Index:
    name: str
    unique: bool
    origin: str
    columns: tuple[str, ...]


@dataclass(frozen=True)
class Table:
    name: str
    note: str
    columns: tuple[Column, ...]
    foreign_keys: tuple[ForeignKey, ...]
    indexes: tuple[Index, ...]
    checks: tuple[str, ...]


@dataclass(frozen=True)
class SchemaSnapshot:
    version: int
    tables: tuple[Table, ...]


def _check_expressions(ddl: str) -> tuple[str, ...]:
    """Extract normalized CHECK expressions from a CREATE TABLE statement."""

    expressions: list[str] = []
    cursor = 0
    while True:
        start = ddl.find("CHECK", cursor)
        if start == -1:
            break
        opening = ddl.find("(", start)
        if opening == -1:
            break
        depth = 0
        closing = -1
        for position in range(opening, len(ddl)):
            character = ddl[position]
            if character == "(":
                depth += 1
            elif character == ")":
                depth -= 1
                if depth == 0:
                    closing = position
                    break
        if closing == -1:
            break
        expression = " ".join(ddl[opening + 1 : closing].split())
        expressions.append(expression)
        cursor = closing + 1
    return tuple(expressions)


def _index_columns(connection: sqlite3.Connection, name: str) -> tuple[str, ...]:
    rows = connection.execute(f"PRAGMA index_info({name})").fetchall()
    return tuple(row[2] for row in rows)


def _read_table(connection: sqlite3.Connection, name: str) -> Table:
    ddl_row = connection.execute(
        "SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?", (name,)
    ).fetchone()
    if ddl_row is None or ddl_row[0] is None:
        raise SchemaDocsError(f"physical table {name!r} is missing from the schema")

    columns = tuple(
        Column(
            name=row[1],
            sql_type=(row[2] or "").upper(),
            nullable=not bool(row[3]),
            default=row[4],
            primary_key=bool(row[5]),
        )
        for row in connection.execute(f"PRAGMA table_info({name})").fetchall()
    )

    foreign_keys = tuple(
        sorted(
            (
                ForeignKey(
                    column=row[3],
                    references_table=row[2],
                    references_column=row[4],
                    on_delete=row[6],
                )
                for row in connection.execute(
                    f"PRAGMA foreign_key_list({name})"
                ).fetchall()
            ),
            key=lambda key: key.column,
        )
    )

    indexes: list[Index] = []
    for row in connection.execute(f"PRAGMA index_list({name})").fetchall():
        index_name, unique, origin = row[1], bool(row[2]), row[3]
        if origin == "pk":
            continue
        indexes.append(
            Index(
                name=index_name,
                unique=unique,
                origin=origin,
                columns=_index_columns(connection, index_name),
            )
        )
    indexes.sort(key=lambda index: index.name)

    return Table(
        name=name,
        note=TABLE_NOTES.get(name, ""),
        columns=columns,
        foreign_keys=foreign_keys,
        indexes=tuple(indexes),
        checks=_check_expressions(ddl_row[0]),
    )


def build_snapshot() -> SchemaSnapshot:
    """Create a temporary database from the schema and read its catalog."""

    with tempfile.TemporaryDirectory(prefix="vt-schema-") as directory:
        path = Path(directory) / "schema.sqlite3"
        Storage(path).initialize()
        connection = sqlite3.connect(path)
        try:
            version = int(connection.execute("PRAGMA user_version").fetchone()[0])
            names = {
                row[0]
                for row in connection.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table'"
                    " AND name NOT LIKE 'sqlite_%'"
                    " AND name NOT LIKE ?",
                    (FTS_SHADOW_PREFIX + "%",),
                ).fetchall()
            }
            unexpected = sorted(names - set(SCHEMA_TABLE_ORDER))
            missing = [name for name in SCHEMA_TABLE_ORDER if name not in names]
            if unexpected:
                raise SchemaDocsError(
                    "document the new physical tables: " + ", ".join(unexpected)
                )
            if missing:
                raise SchemaDocsError(
                    "physical tables missing from the schema: " + ", ".join(missing)
                )
            tables = tuple(
                _read_table(connection, name) for name in SCHEMA_TABLE_ORDER
            )
        finally:
            connection.close()
    return SchemaSnapshot(version=version, tables=tables)


def missing_notes() -> list[str]:
    """Return tables and columns the curated notes do not describe yet."""

    snapshot = build_snapshot()
    missing: list[str] = []
    for table in snapshot.tables:
        if not table.note:
            missing.append(f"{table.name} (table)")
        notes = COLUMN_NOTES.get(table.name, {})
        for column in table.columns:
            if not notes.get(column.name):
                missing.append(f"{table.name}.{column.name}")
        stale = sorted(set(notes) - {column.name for column in table.columns})
        missing.extend(f"{table.name}.{name} (stale note)" for name in stale)
    stale_tables = sorted(set(COLUMN_NOTES) - set(SCHEMA_TABLE_ORDER))
    missing.extend(f"{name} (stale table notes)" for name in stale_tables)
    return sorted(missing)


def _column_key(table: Table, column: Column) -> str:
    if column.primary_key:
        return "PK"
    if any(key.column == column.name for key in table.foreign_keys):
        return "FK"
    return ""


def _render_dot_node(table: Table) -> list[str]:
    lines = [
        f'  {table.name} [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="3" BGCOLOR="white">',
        f'      <TR><TD BGCOLOR="#e6e6e6" COLSPAN="2"><B>{table.name}</B></TD></TR>',
    ]
    for column in table.columns:
        key = _column_key(table, column)
        lines.append(
            f'      <TR><TD ALIGN="LEFT">{column.name}</TD>'
            f'<TD ALIGN="LEFT">{key}</TD></TR>'
        )
    lines.append("    </TABLE>>];")
    return lines


def render_dot(snapshot: SchemaSnapshot | None = None) -> str:
    """Render the committed Graphviz source for the physical model."""

    snapshot = snapshot or build_snapshot()
    lines = [
        "digraph physical_data_model {",
        "  // Generated by scripts/build_data_model.py from the Storage schema; do not edit.",
        '  graph [rankdir=LR, splines=true, nodesep=0.16, ranksep=0.52, fontname="Helvetica", fontsize=9,',
        '         bgcolor="white", pad=0.10];',
        '  node [fontname="Helvetica", fontsize=7.5, shape=plaintext];',
        '  edge [fontname="Helvetica", fontsize=7, color="#333333", arrowsize=0.55,',
        "        dir=both, arrowtail=tee, arrowhead=crow];",
        "  // Physical SQLite schema. The logical model is docs/figures/prd-er.dot.",
    ]
    for table in snapshot.tables:
        lines.extend(_render_dot_node(table))
    for table in snapshot.tables:
        for key in table.foreign_keys:
            lines.append(
                f'  {key.references_table} -> {table.name}'
                f' [label="{key.column}"];'
            )
    lines.append("}")
    return "\n".join(lines) + "\n"


def _render_columns_table(table: Table) -> list[str]:
    lines = [
        "| Column | Type | Null | Key | Notes |",
        "|---|---|---|---|---|",
    ]
    for column in table.columns:
        key = _column_key(table, column)
        note = COLUMN_NOTES[table.name][column.name]
        lines.append(
            f"| `{column.name}` | {column.sql_type or '-'} |"
            f" {'yes' if column.nullable else 'no'} | {key or '-'} | {note} |"
        )
    return lines


