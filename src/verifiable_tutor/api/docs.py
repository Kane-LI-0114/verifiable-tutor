"""Generate and check the committed API documentation bundle.

``docs/api/`` is the maintained, offline Swagger UI bundle. The OpenAPI schema
is exported deterministically from the app factory (no lifespan, no database,
no network), and the generated page embeds it so it can be opened offline.
The Swagger UI assets under ``docs/api/vendor/swagger-ui/`` are pinned and
vendored once by ``scripts/vendor_swagger_ui.sh``.
"""

from __future__ import annotations

import hashlib
import html
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
DOCS_DIR = REPO_ROOT / "docs" / "api"
SPEC_PATH = DOCS_DIR / "openapi.json"
INDEX_PATH = DOCS_DIR / "index.html"
VENDOR_DIR = DOCS_DIR / "vendor" / "swagger-ui"
SWAGGER_ASSETS = (
    "swagger-ui-bundle.js",
    "swagger-ui.css",
    "favicon-32x32.png",
    "LICENSE",
)

# Only used to satisfy the fail-closed settings loader during export; the
# OpenAPI schema does not depend on the value.
SESSION_SECRET_FOR_EXPORT = "openapi-docs-export"

_INLINE_SPEC_ID = "openapi-spec"
_INDEX_TEMPLATE = """<!-- Generated by scripts/build_api_docs.py; do not edit. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="stylesheet" href="vendor/swagger-ui/swagger-ui.css">
<link rel="icon" type="image/png" href="vendor/swagger-ui/favicon-32x32.png">
</head>
<body>
<div id="swagger-ui"></div>
<script type="application/json" id="{spec_id}">{spec}</script>
<script src="vendor/swagger-ui/swagger-ui-bundle.js"></script>
<script>
window.addEventListener("load", function () {{
  window.ui = SwaggerUIBundle({{
    spec: JSON.parse(document.getElementById("{spec_id}").textContent),
    dom_id: "#swagger-ui",
    deepLinking: true,
    presets: [SwaggerUIBundle.presets.apis],
    layout: "BaseLayout",
  }});
}});
</script>
</body>
</html>
"""


class DocsBundleError(RuntimeError):
    """Raised when the bundle cannot be generated from the local files."""


def _repo_root(repo_root: str | Path | None) -> Path:
    return Path(repo_root) if repo_root is not None else REPO_ROOT


def build_openapi_spec(repo_root: str | Path | None = None) -> dict[str, Any]:
    """Build the app and return its OpenAPI schema without running the app."""

    from ..settings import load_settings
    from .factory import create_app

    root = _repo_root(repo_root)
    settings = load_settings(
        repo_root=root,
        env={"SESSION_SECRET": SESSION_SECRET_FOR_EXPORT},
    )
    app = create_app(settings)
    return app.openapi()


def dump_spec(spec: dict[str, Any]) -> str:
    """Serialize the schema deterministically, without timestamps or paths."""

    return json.dumps(spec, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_index_html(spec: dict[str, Any]) -> str:
    """Render the offline Swagger UI page with the schema embedded."""

    title = html.escape(f"{spec.get('info', {}).get('title', 'API')} - Swagger UI")
    inline = json.dumps(spec, ensure_ascii=False).replace("</", "<\\/")
    return _INDEX_TEMPLATE.format(title=title, spec_id=_INLINE_SPEC_ID, spec=inline)


def vendor_problems(repo_root: str | Path | None = None) -> list[str]:
    """Return integrity problems for the vendored Swagger UI assets."""

    root = _repo_root(repo_root)
    vendor = root / "docs" / "api" / "vendor" / "swagger-ui"
    problems: list[str] = []
    version_path = vendor / "VERSION"
    if not version_path.is_file():
        return [f"missing {version_path}"]
    version = version_path.read_text(encoding="utf-8").strip()
    if not version or not version[0].isdigit():
        problems.append(f"invalid Swagger UI version in {version_path}")

    sums_path = vendor / "SHA256SUMS"
    if not sums_path.is_file():
        problems.append(f"missing {sums_path}")
        return problems
    listed: dict[str, str] = {}
    for line in sums_path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2:
            listed[parts[1]] = parts[0]
    if set(listed) != set(SWAGGER_ASSETS):
        problems.append(f"{sums_path} does not list exactly {SWAGGER_ASSETS}")
    for name, expected in listed.items():
        path = vendor / name
        if not path.is_file():
            problems.append(f"missing {path}")
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != expected:
            problems.append(f"checksum mismatch for {path}")
    license_path = vendor / "LICENSE"
    if license_path.is_file() and "Apache License" not in license_path.read_text(
        encoding="utf-8"
    ):
        problems.append(f"{license_path} is not the Apache-2.0 license text")
    return problems


def check_spec(repo_root: str | Path | None = None) -> list[str]:
    """Return a list of staleness problems for the committed schema."""

    root = _repo_root(repo_root)
    path = root / "docs" / "api" / "openapi.json"
    if not path.is_file():
        return [f"missing {path}"]
    expected = dump_spec(build_openapi_spec(root))
    if path.read_text(encoding="utf-8") != expected:
        return [f"stale {path}"]
    return []


def check_bundle(repo_root: str | Path | None = None) -> list[str]:
    """Return staleness problems for the schema and the generated page."""

    root = _repo_root(repo_root)
    problems = check_spec(root)
    spec_path = root / "docs" / "api" / "openapi.json"
    index_path = root / "docs" / "api" / "index.html"
    if not index_path.is_file():
        problems.append(f"missing {index_path}")
    elif spec_path.is_file():
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
        expected = render_index_html(spec)
        if index_path.read_text(encoding="utf-8") != expected:
            problems.append(f"stale {index_path}")
    return problems


def write_spec(repo_root: str | Path | None = None) -> Path:
    """Write the committed schema from the current app and return its path."""

    root = _repo_root(repo_root)
    path = root / "docs" / "api" / "openapi.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_spec(build_openapi_spec(root)), encoding="utf-8")
    return path


def write_index(repo_root: str | Path | None = None) -> Path:
    """Render the offline page from the committed schema."""

    root = _repo_root(repo_root)
    spec_path = root / "docs" / "api" / "openapi.json"
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    path = root / "docs" / "api" / "index.html"
    path.write_text(render_index_html(spec), encoding="utf-8")
    return path


def write_bundle(repo_root: str | Path | None = None) -> list[Path]:
    """Validate the vendored assets, then write the schema and the page."""

    root = _repo_root(repo_root)
    problems = vendor_problems(root)
    if problems:
        raise DocsBundleError(
            "the vendored Swagger UI assets are missing or corrupt; run "
            "bash scripts/vendor_swagger_ui.sh (first problem: "
            f"{problems[0]})"
        )
    return [write_spec(root), write_index(root)]
